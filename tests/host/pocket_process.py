"""CLI/HTTP driver of a real unmodified Pocket process; never creates a Harness or reads its DB."""
import http.cookiejar
import json
import os
from pathlib import Path
import re
import selectors
import signal
import socket
import subprocess
import time
import urllib.request


class PocketProcess:
    def __init__(self, fixture_path):
        self.path = Path(fixture_path).resolve()
        self.fixture = json.loads(self.path.read_text())
        self.source = Path(self.fixture["source"])
        self.transcript = b""
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def redact(self, value):
        text = re.sub(r"[?&]token=[A-Za-z0-9._~-]+", "?token=<REDACTED>", str(value))
        for original, replacement in [(str(self.path.parent), "<SANDBOX>"),
                (str((self.source / "node_modules").resolve()), "<PUBLIC_DEPENDENCIES>")]:
            text = text.replace(original, replacement)
        return text

    def __enter__(self):
        sock = socket.socket()
        sock.bind(("127.0.0.1", 0))
        self.port = sock.getsockname()[1]
        sock.close()
        self.base = f"http://127.0.0.1:{self.port}"
        command = ["node", str(self.source / "bin/pi-pocket.js"), "--access", "local", "--port", str(self.port),
                   "--cwd", self.fixture["project"], "--data", self.fixture["data"]]
        self.process = subprocess.Popen(command, cwd=self.fixture["project"], env=self.fixture["env"],
            stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, start_new_session=True)
        self.selector = selectors.DefaultSelector()
        self.selector.register(self.process.stdout, selectors.EVENT_READ)
        deadline = time.monotonic() + 35
        try:
            while time.monotonic() < deadline:
                for key, _ in self.selector.select(.2):
                    self.transcript += os.read(key.fileobj.fileno(), 65536)
                match = re.search(rb"[?&]token=([A-Za-z0-9._~-]+)", self.transcript)
                if match:
                    # Generated by THIS isolated app; never log or read the author's token/config.
                    token = match.group(1).decode()
                    with self.opener.open(self.base + "/login?token=" + token, timeout=10) as response:
                        assert response.status == 200
                        response.read()
                    return self
                if self.process.poll() is not None:
                    break
            raise RuntimeError("Public Pocket did not start: " + self.redact(self.transcript.decode(errors="replace")))
        except BaseException:
            self.__exit__()
            raise

    def request(self, path, body=None):
        assert path.startswith("/api/"), "Fixture API requests must remain on its own server"
        encoded = None if body is None else json.dumps(body).encode()
        request = urllib.request.Request(self.base + path, data=encoded,
            headers={"Content-Type": "application/json", "X-Pocket": "1", "Origin": self.base})
        with self.opener.open(request, timeout=15) as response:
            return json.load(response)

    def __exit__(self, *_):
        if self.process.poll() is None:
            self.process.send_signal(signal.SIGINT)
        try:
            self.transcript += self.process.communicate(timeout=15)[0]
        except subprocess.TimeoutExpired:
            os.killpg(self.process.pid, signal.SIGTERM)
            self.transcript += self.process.communicate(timeout=10)[0]
        self.selector.close()
        evidence = Path(self.fixture["evidence"])
        (evidence / "pocket-real-process.log").write_text(self.redact(self.transcript.decode(errors="replace")))
